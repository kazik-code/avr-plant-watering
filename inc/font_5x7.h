static inline uint8_t font_5x7_get_column(char character, uint8_t column)
{
    uint8_t code = (uint8_t)character;

    if (code < (uint8_t)FONT_5X7_FIRST_CHAR ||
        code > (uint8_t)FONT_5X7_LAST_CHAR ||
        column >= FONT_5X7_WIDTH) {
        return 0x00;
    }

    return pgm_read_byte(&font_5x7[code - FONT_5X7_FIRST_CHAR][column]);
}
